/**
 * Regenerate golden-image baselines for tests/browser/golden.spec.ts.
 *
 *   npm run update:goldens                 # chromium + firefox
 *   npm run update:goldens -- --engine=chromium
 *
 * Writes docs/evidence/golden/<fixture>.<engine>.png plus manifest.json.
 * IMPORTANT: this script must mirror the capture steps in golden.spec.ts
 * (openEditor -> fonts.ready -> import -> image settle -> toDataURL).
 * The ready check is `npm run test:browser` immediately after regeneration.
 */
const { chromium, firefox } = require('@playwright/test');
const { spawn } = require('node:child_process');
const crypto = require('node:crypto');
const fs = require('node:fs');
const path = require('node:path');

const repo = path.join(__dirname, '..');
const FIXTURE_DIR = path.join(repo, 'tests', 'fixtures', 'golden');
const GOLDEN_DIR = path.join(repo, 'docs', 'evidence', 'golden');
const PORT = Number(process.env.GOLDEN_PORT ?? 4180);
const BASE = `http://127.0.0.1:${PORT}`;

const engines = {
  chromium: { type: chromium, device: {} },
  firefox: { type: firefox, device: {} },
};

const engineArg = (process.argv.find((a) => a.startsWith('--engine=')) ?? '').split('=')[1];
const requested = engineArg && engineArg !== 'all' ? [engineArg] : ['chromium', 'firefox'];
for (const name of requested) {
  if (!engines[name]) {
    console.error(`Unknown engine "${name}". Use chromium, firefox or all.`);
    process.exit(1);
  }
}

const sha256 = (buffer) => crypto.createHash('sha256').update(buffer).digest('hex');

async function waitForServer() {
  for (let i = 0; i < 100; i += 1) {
    try {
      const res = await fetch(`${BASE}/index.html`);
      if (res.ok) return;
    } catch {
      // not up yet
    }
    await new Promise((r) => setTimeout(r, 100));
  }
  throw new Error(`server did not start on ${BASE}`);
}

async function captureFixture(page, fixtureJson) {
  await page.evaluate((text) => {
    app = restoreFrom(text);
    refresh();
  }, fixtureJson);
  await page.waitForFunction(() =>
    app.slides.every((s) => !s.image || Boolean(getCachedImage(s.image))),
  );
  await page.evaluate(() => refresh());
  return page.evaluate(() => {
    const canvas = document.getElementById('postCanvas');
    return {
      dataUrl: canvas.toDataURL('image/png'),
      width: canvas.width,
      height: canvas.height,
    };
  });
}

(async () => {
  fs.mkdirSync(GOLDEN_DIR, { recursive: true });
  const fixtures = fs
    .readdirSync(FIXTURE_DIR)
    .filter((f) => f.endsWith('.rgstudio.json'))
    .sort();

  const server = spawn('node', ['tools/serve.cjs', '.', String(PORT)], {
    cwd: repo,
    stdio: 'ignore',
  });

  const manifest = {
    note: 'Generated by npm run update:goldens. Baselines are engine-specific; compare via tests/browser/golden.spec.ts tolerances.',
    generatedAt: new Date().toISOString(),
    playwrightVersion: require('@playwright/test/package.json').version,
    engines: {},
  };

  try {
    await waitForServer();
    for (const name of requested) {
      const engine = engines[name].type;
      console.log(`\n[${name}] capturing ${fixtures.length} fixtures...`);
      const browser = await engine.launch();
      const context = await browser.newContext();
      const page = await context.newPage();
      await page.goto(`${BASE}/index.html`);
      await page.waitForSelector('#templateGrid .template-card');
      await page.waitForFunction(
        () => document.querySelectorAll('#templateGrid .template-card').length === 40,
      );
      await page.evaluate(() => document.fonts?.ready ?? Promise.resolve());

      const entries = [];
      for (const file of fixtures) {
        const id = file.replace(/\.rgstudio\.json$/, '');
        const json = fs.readFileSync(path.join(FIXTURE_DIR, file), 'utf8');
        const { dataUrl, width, height } = await captureFixture(page, json);
        const buffer = Buffer.from(dataUrl.replace(/^data:image\/png;base64,/, ''), 'base64');
        const outPath = path.join(GOLDEN_DIR, `${id}.${name}.png`);
        fs.writeFileSync(outPath, buffer);
        entries.push({ id, width, height, sha256: sha256(buffer) });
        console.log(`  ${id}.${name}.png  ${width}x${height}  ${buffer.length} bytes`);
      }
      manifest.engines[name] = entries;
      await browser.close();
    }

    fs.writeFileSync(
      path.join(GOLDEN_DIR, 'manifest.json'),
      JSON.stringify(manifest, null, 2) + '\n',
    );
    console.log('\nmanifest.json written');
  } finally {
    server.kill();
  }
})().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
